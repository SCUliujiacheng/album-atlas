import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
async function list(dir) {
  const entries = await readdir(join(root,dir), {withFileTypes:true});
  const groups = await Promise.all(entries.map(x => x.isDirectory() ? list(dir + '/' + x.name) : [dir + '/' + x.name]));
  return groups.flat();
}
const assets = ['index.html','app.webmanifest','docs/crop-practice.zip',...(await list('src')),...(await list('assets')),...(await list('vendor'))].sort();
const hash = createHash('sha256');
for (const file of [...assets,'sw.js']) {
  const bytes = await readFile(join(root,file));
  // Git normalizes these text files to LF. Windows working copies and clean
  // Linux checkouts must calculate the same offline release identifier.
  const normalized = !file.startsWith('vendor/') && /\.(html|js|css|svg|md|webmanifest)$/.test(file)
    ? bytes.toString('utf8').replace(/\r\n/g,'\n') : bytes;
  hash.update(file).update(normalized);
}
const generated = '// Generated by npm run build:offline\nconst PRECACHE_REV = ' + JSON.stringify(hash.digest('hex').slice(0,16))
  + ';\nconst PRECACHE = ' + JSON.stringify(assets, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (generated !== await readFile(join(root,'precache.js'),'utf8')) throw new Error('Offline manifest is stale. Run npm run build:offline.');
} else await writeFile(join(root,'precache.js'), generated);
